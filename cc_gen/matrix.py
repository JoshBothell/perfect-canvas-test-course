"""Test matrix: a human-readable Markdown matrix per theme, and a theme-independent *signature*.

``render`` writes the per-theme doc (``theme.yaml`` ``matrix_doc``). ``signature`` reduces a course
to the Canvas settings it exercises, dropping everything that is theme content (titles, text,
keys, URLs, file names), so ``cc matrix --compare A B`` proves two themes have the same test matrix.
"""

from __future__ import annotations

import difflib
import json

from .content import Course, file_id
from .ids import use_namespace


def _md(s: str) -> str:
    return str(s).replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;")


def render(course: Course) -> str:
    d = course.dates
    out = [
        "# Test Matrix",
        "",
        f"Generated by `uv run cc matrix --theme {course.theme.name}` from `themes/{course.theme.root.name}/`. Do not edit by hand.",
        "Every item exists to exercise a Canvas feature. The theme content is filler.",
        "",
        f"Dates shown are for anchor **{d.anchor.isoformat()}** in **{d.tz.key}**. Rebuilding with another `--anchor` shifts them all.",
        "",
    ]
    for m in course.modules:
        state = "published" if m.get("published", True) else "**unpublished**"
        bits = [state]
        if m.get("unlock_at"):
            bits.append(f"unlocks {d.local(m['unlock_at']):%Y-%m-%d %H:%M %Z}")
        if m.get("prerequisites"):
            bits.append("prerequisites: " + ", ".join(m["prerequisites"]))
        if m.get("require_sequential_progress"):
            bits.append("sequential progress")
        if m.get("requires_lti"):
            bits.append("only built with `lti.yaml`")
        out += [f"## {_md(m['title'])}", "", " · ".join(bits), ""]
        if m.get("tests"):
            out += ["Module-level: " + "; ".join(m["tests"]), ""]
        if not m["items"]:
            out += ["_(empty module)_", ""]
            continue
        out += ["| # | Item | Type | Requirement | Tests |", "|---|---|---|---|---|"]
        for i, it in enumerate(m["items"], 1):
            req = (it.get("requirement") or "") + (f" ≥ {it['min_score']}" if it.get("min_score") else "") \
                + (f" ≥ {it['min_percentage']}%" if it.get("min_percentage") else "")
            title = ("&nbsp;&nbsp;" * it["indent"]) + _md(it["title"] if len(it["title"]) < 90 else it["title"][:87] + "…")
            out.append(f"| {i} | {title} | {it['content_type'].replace('ContextModule', '')} | {req} | {_md('; '.join(it['tests']))} |")
        out.append("")

    out += ["## Course-level objects", ""]
    out.append("| Object | Details |")
    out.append("|---|---|")
    for a in course.announcements.values():
        extra = []
        if a.get("delayed_post_at"):
            extra.append(f"delayed post {d.local(a['delayed_post_at']):%Y-%m-%d %H:%M}")
        if a.get("locked"):
            extra.append("comments locked")
        out.append(f"| Announcement: {_md(a['title'])} | {', '.join(extra) or 'posted'} |")
    for e in course.events:
        kind = "all-day" if e.get("all_day") else f"weekly ×{e['repeat_weekly']} (series)" if e.get("repeat_weekly", 1) > 1 else "timed"
        out.append(f"| Calendar event: {_md(e['title'])} | {kind} |")
    for g in course.assignment_groups.values():
        out.append(f"| Assignment group: {_md(g['title'])} | weight {g['weight']}%{'; rules ' + _md(str(g['rules'])) if g.get('rules') else ''} |")
    for gs in course.grading_standards.values():
        out.append(f"| Grading scheme: {_md(gs['title'])} | {'points-based' if gs.get('points_based') else 'percentage'} |")
    for r in course.rubrics.values():
        flags = [k for k in ("free_form_criterion_comments", "hide_score_total") if r.get(k)]
        out.append(f"| Rubric: {_md(r['title'])} | {len(r['criteria'])} criteria{'; ' + ', '.join(flags) if flags else ''} |")
    for o in course.outcomes.values():
        out.append(f"| Outcome: {_md(o['title'])} | {o['calculation_method']} |")
    for b in course.banks.values():
        out.append(f"| Question bank: {_md(b['title'])} | {len(b['questions'])} questions |")
    for p in course.pages.values():
        if not any(it.get("ref_id") == p["id"] for m in course.modules for it in m["items"]):
            out.append(f"| Page outside modules: {_md(p['title'])} | {'unpublished' if p.get('published') is False else 'published'} |")
    out += [
        "",
        "## Created by the seeder (not representable in a cartridge)",
        "",
        "See `seeder/roster.yaml`: sections (one with its own dates), teacher/TA (section-limited)/designer/observer,",
        "students incl. multi-section, inactive, concluded, unicode and very long names; group membership and a",
        "self-signup group set; section/student/group overrides; module progress, discussion posts, submissions",
        "(text/URL/file), grades in every grading type, rubric assessments, an excused submission, a hidden",
        "(manually posted) grade, a moderated-grading final grader, and an optional LTI 1.3 tool install.",
        "",
    ]
    return "\n".join(out)


# ------------------------------------------------------------------ signature
# Fields that are theme content: dropped from the signature.
TEXT = {"title", "item_title", "body", "description", "message", "text", "name", "key", "id", "meta_id", "assignment_id",
        "url", "answers", "feedback", "pairs", "distractors", "blanks", "formula", "variables", "sets", "answer",
        "questions", "items", "type", "position", "syllabus", "course_code", "label", "series_uuid", "access_code",
        "long_description", "legal_copyright", "custom", "launch_url", "domain", "privacy_level", "client_id", "consumer_key",
        "shared_secret", "location", "comments"}
# Fields whose value is a key into another theme registry: only their presence is kept.
REFS = {"group", "rubric", "grading_standard", "group_category", "annotatable_file", "bank", "path", "tool",
        "default_grading_standard", "image", "banner_image", "outcome", "never_drop", "prerequisites", "display_name",
        "tag", "resource_id"}  # tag/resource_id: opaque AGS line-item identifiers a theme names freely


CATALOG_MIN = 386  # identification bank coverage in the reference (Pokémon) theme

# Module-item fields that inline YAML also leaves on the object (already in the item line).
ITEM_ONLY = {"indent", "requirement", "min_score", "min_percentage", "item_published", "new_tab", "ref", "tests"}


def _settings(obj: dict, drop=frozenset(TEXT)) -> dict:
    out = {}
    for k, v in sorted(obj.items()):
        if k in drop or v is None:
            continue
        if k in REFS:
            out[k] = f"<{len(v)} refs>" if isinstance(v, list) else "<ref>"
        elif isinstance(v, dict):
            out[k] = _settings(v, drop)
        elif isinstance(v, list) and v and isinstance(v[0], dict):
            out[k] = [_settings(x, drop) for x in v]
        else:
            out[k] = v
    return out


def _question(q: dict) -> dict:
    sig = {"type": q["type"], "points": q.get("points"), "pick": q.get("pick"), "bank": "<ref>" if q.get("bank") else None,
           "generated": q.get("generated"), "inline": len(q.get("questions") or []) or None,
           "feedback": sorted(q.get("feedback") or {}), "answers": len(q.get("answers") or q.get("pairs") or q.get("blanks") or [])}
    if q["type"] in ("numerical", "calculated"):
        sig["numeric"] = _settings({k: v for k, v in q.items() if k in ("tolerance", "decimal_places", "forms")})
        sig["answer_shapes"] = sorted({k for a in q.get("answers") or [] if isinstance(a, dict) for k in a})
    return {k: v for k, v in sig.items() if v not in (None, [], 0)}


def _dump(x) -> str:
    return json.dumps(x, ensure_ascii=False, sort_keys=True, default=str)


def signature(course: Course, ignore_tests: bool = False) -> list[str]:
    """One line per Canvas-relevant fact, in course order, with all theme content removed.

    ``ignore_tests`` also drops the ``tests:`` annotations (use it when a theme rewords them)."""
    c = course
    drop = TEXT | ({"tests"} if ignore_tests else set())
    S = lambda obj, extra=frozenset(): _settings(obj, drop | extra)
    with use_namespace(c.theme.namespace):
        file_meta = {file_id(p): meta for p, meta in c.files.items()}
    pos = {m["key"]: i for i, m in enumerate(c.modules, 1)}
    by_id = {}
    for reg in (c.pages, c.assignments, c.discussions, c.quizzes):
        by_id.update({o["id"]: o for o in reg.values()})
    # catalog size only matters up to the contract minimum (a bigger catalog exercises nothing new)
    n = len(c.catalog)
    lines = [f"catalog: {'>=' + str(CATALOG_MIN) if n >= CATALOG_MIN else n} entries in groups {sorted({e['group'] for e in c.catalog})}"]
    for m in c.modules:
        head = S({k: v for k, v in m.items() if k != "prerequisites"})
        head["prerequisites"] = [pos.get(p) for p in m.get("prerequisites") or []]
        lines.append(f"module {m['position']}: {_dump(head)}")
        for i, it in enumerate(m["items"], 1):
            item = S({k: v for k, v in it.items() if k not in ("ref_id",)})
            obj = by_id.get(it.get("ref_id"))
            if obj is not None:
                item["object"] = S(obj, ITEM_ONLY)
                if obj.get("questions") is not None:
                    item["object"]["questions"] = [_question(q) for q in obj["questions"]]
            if it["content_type"] == "Attachment":
                item["file"] = S(file_meta.get(it["ref_id"], {}))
            lines.append(f"  item {m['position']}.{i}: {_dump(item)}")
    lines.append(f"settings: {_dump(S({k: v for k, v in c.settings.items() if k not in ('assignment_groups', 'grading_standards', 'rubrics', 'outcomes', 'events', 'announcements', 'files', 'folders', 'pages', 'assignments', 'discussions')}))}")
    for g in c.assignment_groups.values():
        lines.append(f"assignment group: {_dump(S(g))}")
    for gs in c.grading_standards.values():
        lines.append(f"grading standard: {_dump({'points_based': bool(gs.get('points_based')), 'entries': len(gs.get('data') or gs.get('scheme') or [])})}")
    for r in c.rubrics.values():
        lines.append(f"rubric: {_dump(S(r))}")
    for o in c.outcomes.values():
        lines.append(f"outcome: {_dump(S(o))}")
    for e in c.events:
        lines.append(f"event: {_dump(S(e))}")
    for a in c.announcements.values():
        lines.append(f"announcement: {_dump(S(a))}")
    banks = []  # sorted: bank order follows quiz keys, which are theme content
    for b in c.banks.values():
        shapes: dict[str, int] = {}
        for q in b["questions"]:
            shapes[_dump(_question(q))] = shapes.get(_dump(_question(q)), 0) + 1
        size = "one per catalog entry" if len(shapes) == 1 and len(b["questions"]) == len(c.catalog) else len(b["questions"])
        banks.append(f"bank: {size} questions: " + "; ".join(f"{k}" if size != len(b['questions']) else f"{n}× {k}" for k, n in shapes.items()))
    lines += sorted(banks)
    lines.append(f"files meta: {sorted(_dump(S(v)) for v in c.files.values() if len(v) > 1)}")
    lines.append(f"folders: {sorted(_dump(S(v)) for v in (c.settings.get('folders') or {}).values())}")
    for p in c.pages.values():
        if not any(it.get("ref_id") == p["id"] for m in c.modules for it in m["items"]):
            lines.append(f"page outside modules: {_dump(S(p))}")
    return lines


def compare(a: Course, b: Course, ignore_tests: bool = False) -> list[str]:
    """Unified diff of two signatures (empty = identical test matrix)."""
    return list(difflib.unified_diff(signature(a, ignore_tests), signature(b, ignore_tests),
                                     f"theme {a.theme.name}", f"theme {b.theme.name}", lineterm="", n=1))
